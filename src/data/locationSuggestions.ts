/**
 * Mencari saran lokasi menggunakan PREFIX MATCHING.
 * Minimal query 2 karakter.
 */
export function getPrefixLocationSuggestions(query: string, maxResults = 5): LocationSuggestion[] {
  const q = query.trim().toLowerCase();
  if (q.length < 2) return [];

  // Ambil kata terakhir jika user mengetik kalimat (misal: "kos dekat pols" -> "pols")
  const words = q.split(/\s+/);
  const targetWord = words[words.length - 1];

  const matched: LocationSuggestion[] = [];
  const seenLabels = new Set<string>();

  for (const item of LOCATION_DATA) {
    const keyLower = item.key.toLowerCase();
    const labelLower = item.label.toLowerCase();

    // Cek apakah key atau label diawali dengan query penuh ATAU diawali dengan kata terakhir
    const isPrefixMatch =
      keyLower.startsWith(q) ||
      labelLower.startsWith(q) ||
      (targetWord.length >= 2 && (keyLower.startsWith(targetWord) || labelLower.startsWith(targetWord)));

    if (isPrefixMatch && !seenLabels.has(item.label)) {
      seenLabels.add(item.label);
      matched.push(item);
      if (matched.length >= maxResults) break;
    }
  }

  return matched;
}